def test_names_resolve_short_to_full():
    n = scene.Names({"e1": "Elder Taan", "e2": "Captain Iven Strake", "e3": "Taan's Goat"})
    assert n.resolve("taan", ["Elder Taan", "Taan's Goat"])[0] == "Elder Taan"
